static const GoodixProfile profiles[] = {
  /* 55a2 readers ship with either firmware. The original driver used this
   * same configuration, geometry and timing for both. Other GF32xx firmware is
   * refused rather than guessed at. */
  {0x55a2, "GF3206_RTSEC_APP_10052", 56, 176, 4, 1024, 600,
   config_55a2, sizeof (config_55a2)},
  {0x55a2, "GF3206_RTSEC_APP_10062", 56, 176, 4, 1024, 600,
   config_55a2, sizeof (config_55a2)},
};

const GoodixProfile *
goodix_profile_lookup (guint16 pid, const gchar *firmware)
{
  for (gsize i = 0; i < G_N_ELEMENTS (profiles); i++)
    if (profiles[i].pid == pid && g_strcmp0 (profiles[i].firmware, firmware) == 0)
      return &profiles[i];
  return NULL;
}
